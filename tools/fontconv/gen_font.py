FIRST, LAST = 32, 126


def preview(text):
    """Render a string as ASCII art so glyphs can be eyeballed."""
    rows = [""] * 8
    for ch in text:
        g = GLYPHS.get(ord(ch), GLYPHS[32])
        for r in range(8):
            bits = "".join("#" if g[r] & (0x80 >> c) else "." for c in range(8))
            rows[r] += bits + " "
    return "\n".join(rows)


def emit_zig():
    out = [
        "//! Orange OS console font — 8x8 bitmap, printable ASCII 32..126.",
        "//!",
        "//! GENERATED by tools/fontconv/gen_font.py — do not edit by hand.",
        "//! Glyph data is original to this project (MIT OR Apache-2.0).",
        "//!",
        "//! Bit order: MSB is the leftmost pixel of each row.",
        "",
        "pub const WIDTH: usize = 8;",
        "pub const HEIGHT: usize = 8;",
        f"pub const FIRST: u8 = {FIRST};",
        f"pub const LAST: u8 = {LAST};",
        "",
        f"pub const glyphs = [{LAST - FIRST + 1}][8]u8{{",
    ]
    for code in range(FIRST, LAST + 1):
        g = GLYPHS.get(code, GLYPHS[32])
        label = chr(code) if code != 32 else "space"
        if label in ("\\",):
            label = "backslash"
        body = ", ".join(f"0x{b:02X}" for b in g)
        out.append(f"    .{{ {body} }}, // {label}")
    out.append("};")
    out.append("")
    out.append("/// Returns the glyph for `c`, falling back to space for anything")
    out.append("/// outside the printable range.")
    out.append("pub fn glyph(c: u8) *const [8]u8 {")
    out.append("    if (c < FIRST or c > LAST) return &glyphs[0];")
    out.append("    return &glyphs[c - FIRST];")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    import sys

    if "--preview" in sys.argv:
        i = sys.argv.index("--preview")
        print(preview(sys.argv[i + 1] if len(sys.argv) > i + 1 else "Orange OS"))
    else:
        with open("kernel/drivers/video/font.zig", "w") as f:
            f.write(emit_zig())
        print(f"wrote kernel/drivers/video/font.zig ({LAST - FIRST + 1} glyphs)")
